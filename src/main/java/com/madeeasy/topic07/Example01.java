package com.madeeasy.topic07;

public class Example01 {

    public static void add(int a, int b) {
        int c = a + b; // 30 = 10+20
        System.out.println(c); // 30
    }

    static void main() {
        int a = 10;
        int b = 20;
        add(a, b);
        int score = 40;
        score = 55;
        score = score + 10;
        System.out.println(score); // 65
    }
}
